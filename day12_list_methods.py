# Day 12 - List methods

numbers = [30, 10, 50]

# add elements
numbers.append(40)
numbers.insert(1, 20)

print("After adding:", numbers)

# remove elements
numbers.remove(10)
numbers.pop()

print("After removing:", numbers)

# sort list
numbers.sort()
print("Sorted:", numbers)

# reverse list
numbers.reverse()
print("Reversed:", numbers)
